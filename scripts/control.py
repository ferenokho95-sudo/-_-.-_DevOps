"""Host Docker orchestration. All Docker calls target the forwarded socket.

No host-relative config mounts: files are staged into named Docker volumes.
HTTP checks run on the host daemon's Docker network, not Dagger's network.
"""
import base64
import json
import os
import re
import subprocess
import sys
import time
import uuid
from pathlib import Path
from urllib.parse import urlencode

ROOT = Path(__file__).resolve().parents[1]
SECRETS = []
HTTP = '''import json,sys,urllib.request,urllib.error
p=json.load(sys.stdin)
req=urllib.request.Request(p['url'],data=p.get('body',None).encode() if p.get('body') is not None else None,headers=p['headers'],method=p['method'])
try:
 with urllib.request.urlopen(req,timeout=10) as r: print(r.read().decode())
except urllib.error.HTTPError as e:
 print('HTTP status '+str(e.code),file=sys.stderr);sys.exit(1)
'''

def docker(*args, data=None, check=True):
    result = subprocess.run(["docker", *args], input=data, text=True,
                            capture_output=True, check=False)
    if check and result.returncode:
        diagnostic = result.stderr or result.stdout
        for secret in sorted(SECRETS, key=len, reverse=True):
            diagnostic = diagnostic.replace(secret, "[REDACTED]")
        raise RuntimeError(f"Docker operation {args[0]} failed (exit {result.returncode}):\n{diagnostic[-6000:]}")
    return result.stdout

def credentials():
    path = Path(os.environ.get("CREDENTIALS_FILE", "/run/credentials"))
    values = {}
    for line in path.read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            key, value = line.split("=", 1)
            if not re.fullmatch(r"[a-f0-9]{48}", value):
                raise ValueError("Use credentials generated by scripts/init.py (48 hex chars)")
            values[key] = value
    required = {"DB_ROOT_PASSWORD", "DB_PASSWORD", "EXPORTER_PASSWORD", "GRAFANA_PASSWORD"}
    if set(values) != required:
        raise ValueError("Credential keys do not match expected schema")
    os.environ.update(values)
    SECRETS[:] = values.values()

def compose(layer, *args):
    return docker("compose", "-f", str(ROOT / f"compose.{layer}.json"), *args)

def network():
    existing = docker("network", "inspect", "uptime-metrics", check=False)
    if not existing:
        docker("network", "create", "uptime-metrics")

def stage(layer):
    names = (["db-config", "exporter-init"] if layer == "app" else
             ["prometheus", "blackbox", "mysql"])
    templates = json.loads((ROOT / "config-content.json").read_text())
    writer = """import json,sys,pathlib,os
p=json.load(sys.stdin)
f=pathlib.Path('/config') / p['filename']
t=f.with_suffix('.tmp')
t.write_text(p['content'])
os.chmod(t,0o644)
t.replace(f)
"""
    for name in names:
        volume = "uptime-config-" + name
        docker("volume", "create", volume)
        item = templates[name].copy()
        item["content"] = re.sub(r"\$\{([A-Z_]+):\?required\}",
                                 lambda match: os.environ[match[1]], item["content"])
        docker("run", "--rm", "-i", "--network", "none", "-v", volume + ":/config",
               "python:3.12.9-alpine3.21", "python", "-c", writer, data=json.dumps(item))

def api(path, method="GET", body=None, grafana=True):
    headers = {"Content-Type": "application/json"}
    if grafana:
        token = base64.b64encode(("admin:" + os.environ["GRAFANA_PASSWORD"]).encode()).decode()
        headers["Authorization"] = "Basic " + token
    payload = {"url": ("http://grafana:3000" if grafana else "http://prometheus:9090") + path,
               "method": method, "headers": headers, "body": json.dumps(body) if body is not None else None}
    raw = docker("run", "--rm", "-i", "--network", "uptime-metrics",
                 "python:3.12.9-alpine3.21", "python", "-c", HTTP, data=json.dumps(payload))
    return json.loads(raw)

def wait(description, condition, seconds=180):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        try:
            if condition():
                return
        except (RuntimeError, ValueError, KeyError):
            pass
        time.sleep(3)
    raise TimeoutError(f"Timed out: {description}")

def configure():
    wait("Grafana readiness", lambda: api("/api/health").get("database") == "ok")
    datasource = {"uid": "prometheus", "name": "Prometheus", "type": "prometheus",
                  "access": "proxy", "url": "http://prometheus:9090", "isDefault": True,
                  "jsonData": {"httpMethod": "POST", "timeInterval": "5s"}}
    sources = api("/api/datasources")
    if any(ds.get("uid") == "prometheus" for ds in sources):
        api("/api/datasources/uid/prometheus", "PUT", datasource)
    else:
        api("/api/datasources", "POST", datasource)
    dashboard = json.loads((ROOT / "monitoring/dashboard.json").read_text())
    api("/api/dashboards/db", "POST", {"dashboard": dashboard, "overwrite": True})
    saved = api("/api/dashboards/uid/uptime-health")["dashboard"]
    if saved["panels"][0]["targets"][0]["expr"] != QUERIES["health"]:
        raise RuntimeError("Saved Grafana dashboard health expression differs")
    print("Grafana datasource and dashboard reconciled")

QUERIES = json.loads((ROOT / "monitoring/queries.json").read_text())

def query(expr):
    response = api("/api/datasources/proxy/uid/prometheus/api/v1/query?" + urlencode({"query": expr}))
    if response.get("status") != "success":
        raise RuntimeError("Prometheus query failed")
    return response["data"]["result"]

def value(expr):
    result = query(expr)
    if len(result) != 1:
        raise ValueError("Expected exactly one health series")
    return float(result[0]["value"][1])

def container_id(layer, service):
    cid = compose(layer, "ps", "--all", "--quiet", service).strip()
    if not cid or "\n" in cid:
        raise RuntimeError(f"Expected one container for {service}")
    return cid

def validate():
    def healthy():
        for layer, names in [("app", ["db", "kuma"]), ("monitoring", ["prometheus", "grafana", "node", "cadvisor", "mysqld", "blackbox"])]:
            for name in names:
                state = json.loads(docker("inspect", container_id(layer, name)))[0]["State"]
                if not state["Running"] or state.get("Health", {}).get("Status", "healthy") != "healthy":
                    return False
        if value(QUERIES["health"]) != 1:
            return False
        # Count as well as min: missing scrape targets cannot silently pass.
        if value('count(up)') != 6 or value('min(up)') != 1:
            return False
        if value('min(probe_success{job="http"})') != 1:
            return False
        for metric in ['node_memory_MemTotal_bytes', 'node_filesystem_avail_bytes',
                       'rate(node_cpu_seconds_total{mode="idle"}[1m])']:
            if not query(metric):
                return False
        for service in ("db", "kuma", "prometheus", "grafana", "node", "cadvisor", "mysqld", "blackbox"):
            for metric in ('container_memory_working_set_bytes', 'rate(container_cpu_usage_seconds_total'):
                selector = '{container_label_com_docker_compose_service="' + service + '"}'
                expr = metric + selector + ('[1m])' if metric.startswith('rate(') else '')
                if not query(expr):
                    return False
        return True
    wait("all containers, scrape targets, probes and resource metrics", healthy, 300)
    print("Validation passed: containers, SQL, HTTP, exporters, Grafana API and resource metrics")

def chaos(target, mode):
    if target not in ("db", "kuma") or mode not in ("stop", "crash"):
        raise ValueError("target: db|kuma; mode: stop|crash")
    validate()
    saved = api("/api/dashboards/uid/uptime-health")["dashboard"]
    if saved["panels"][0]["targets"][0]["expr"] != QUERIES["health"]:
        raise RuntimeError("Grafana dashboard differs from the chaos health query")
    cid = container_id("app", target)
    initial = json.loads(docker("inspect", cid))[0]
    if initial["HostConfig"]["RestartPolicy"]["Name"] != "unless-stopped":
        raise RuntimeError("Expected unless-stopped policy")
    # Docker restart manager requires the container to have run successfully >=10s.
    time.sleep(11)
    timeline = []
    def record(stage):
        timeline.append({"stage": stage, "unix_time": time.time(),
                         "health": value(QUERIES["health"]),
                         "target": value(QUERIES["db" if target == "db" else "kuma"])})
    record("before")
    try:
        if mode == "stop":
            docker("stop", "--time", "10", cid)
        else:
            # Pause the whole container: stopping only PID 1 (dumb-init in Kuma)
            # would leave its Node child serving HTTP and hide the outage.
            docker("pause", cid)
        wait("red dashboard health and target status", lambda: value(QUERIES["health"]) == 0 and
             value(QUERIES["db" if target == "db" else "kuma"]) == 0, 120)
        record("down")
        if mode == "stop":
            docker("start", cid)
        else:
            docker("unpause", cid)
            state = json.loads(docker("inspect", cid))[0]["State"]
            host_pid = state["Pid"]
            if host_pid <= 1 or not state["Running"]:
                raise RuntimeError("Refusing to signal an invalid container PID")
            # A Docker kill API call is an intentional/manual stop on this
            # daemon and suppresses restart-policy. Signal the process from the
            # host PID namespace instead, verifying its container cgroup first.
            killer = """import os,signal,sys
pid=int(sys.argv[1]); cid=sys.argv[2]
assert pid > 1 and cid in open('/proc/%d/cgroup' % pid).read(), 'PID does not belong to target container'
os.kill(pid,signal.SIGKILL)
"""
            docker("run", "--rm", "--pid=host", "--privileged", "--network=none",
                   "python:3.12.9-alpine3.21", "python", "-c", killer, str(host_pid), cid)
        validate()
        if mode == "crash":
            after = json.loads(docker("inspect", cid))[0]
            if after["RestartCount"] <= initial["RestartCount"]:
                raise RuntimeError("Docker automatic restart was not observed")
        record("recovered")
        print(json.dumps({"target": target, "mode": mode, "evidence": timeline}, indent=2))
    finally:
        # Ensure a failed assertion does not leave the production app frozen/stopped.
        docker("unpause", cid, check=False)
        docker("start", cid, check=False)

def persistence_check():
    """Verify SQL and Kuma files survive a real container replacement."""
    validate()
    token = uuid.uuid4().hex
    old_db, old_kuma = container_id("app", "db"), container_id("app", "kuma")

    def sql(statement):
        return docker("exec", "-i", container_id("app", "db"), "sh", "-ec",
                      'MYSQL_PWD="$MARIADB_PASSWORD" exec mariadb -ukuma kuma -N', data=statement)

    marker = "/app/data/.persistence-" + token
    try:
        sql("CREATE TABLE IF NOT EXISTS platform_persistence_check (token VARCHAR(32) PRIMARY KEY);"
            f"INSERT INTO platform_persistence_check VALUES ('{token}');")
        docker("exec", old_kuma, "node", "-e",
               "require('fs').writeFileSync(process.argv[1], process.argv[2])", marker, token)
        compose("app", "up", "-d", "--force-recreate", "--wait", "--wait-timeout", "300")
        new_db, new_kuma = container_id("app", "db"), container_id("app", "kuma")
        if old_db == new_db or old_kuma == new_kuma:
            raise RuntimeError("Containers were not replaced")
        if sql(f"SELECT token FROM platform_persistence_check WHERE token='{token}';").strip() != token:
            raise RuntimeError("SQL marker did not survive replacement")
        content = docker("exec", new_kuma, "node", "-e",
                         "process.stdout.write(require('fs').readFileSync(process.argv[1]))", marker)
        if content != token:
            raise RuntimeError("Kuma file did not survive replacement")
        validate()
        print(json.dumps({"persistence": "passed", "sql_marker": "preserved", "kuma_file": "preserved",
                          "db_container_replaced": True, "kuma_container_replaced": True}))
    finally:
        sql(f"DELETE FROM platform_persistence_check WHERE token='{token}';")
        docker("exec", container_id("app", "kuma"), "node", "-e",
               "require('fs').rmSync(process.argv[1], {force:true})", marker, check=False)

def main():
    credentials()
    action = sys.argv[1]
    if action not in {"deploy-app", "deploy-monitoring", "configure-grafana", "deploy-all", "chaos", "validate", "persistence-check"}:
        raise ValueError("Unknown action")
    network()
    if action in ("deploy-app", "deploy-all"):
        stage("app")
        compose("app", "up", "-d", "--force-recreate", "--wait", "--wait-timeout", "300")
        print("Application deployed")
    if action in ("deploy-monitoring", "deploy-all"):
        stage("monitoring")
        compose("monitoring", "up", "-d", "--force-recreate", "--wait", "--wait-timeout", "300")
        print("Monitoring deployed")
    if action in ("configure-grafana", "deploy-all"):
        configure()
    if action in ("deploy-all", "validate"):
        validate()
    if action == "chaos":
        chaos(sys.argv[2], sys.argv[3])
    if action == "persistence-check":
        persistence_check()

if __name__ == "__main__":
    main()
